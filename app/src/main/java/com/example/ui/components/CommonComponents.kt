@Composable
fun CopyableMonoBlock(
    label: String,
    value: String,
    testTag: String,
    modifier: Modifier = Modifier,
    maxLines: Int = Int.MAX_VALUE
) {
    val clipboard = LocalClipboardManager.current
    var copied by remember { mutableStateOf(false) }

    LaunchedEffect(copied) {
        if (copied) {
            delay(1500)
            copied = false
        }
    }

    Column(
        modifier = modifier
            .fillMaxWidth()
            .clip(MaterialTheme.shapes.small)
            .background(CoreLensTheme.extendedColors.codeSurface)
            .border(1.dp, CoreLensTheme.extendedColors.codeBorder, MaterialTheme.shapes.small)
            .padding(start = 12.dp, top = 8.dp, bottom = 10.dp, end = 4.dp)
    ) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.SpaceBetween
        ) {
            Text(
                text = label,
                style = MaterialTheme.typography.labelMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant
            )
            IconButton(
                onClick = {
                    clipboard.setText(AnnotatedString(value))
                    copied = true
                },
                modifier = Modifier
                    .minimumInteractiveComponentSize()
                    .testTag("${testTag}_copy_button")
            ) {
                Icon(
                    imageVector = if (copied) Icons.Rounded.Check else Icons.Outlined.ContentCopy,
                    contentDescription = "Copy $label",
                    tint = if (copied) CoreLensTheme.extendedColors.valid else MaterialTheme.colorScheme.secondary,
                    modifier = Modifier.size(18.dp)
                )
            }
        }
        Text(
            text = value,
            style = MonoTextStyle,
            color = MaterialTheme.colorScheme.onSurface,
            maxLines = maxLines,
            overflow = TextOverflow.Ellipsis,
            modifier = Modifier.padding(end = 8.dp)
        )
    }
}

@Composable
fun KeyValueRow(
    keyLabel: String,
    valueText: String,
    modifier: Modifier = Modifier,
    monoValue: Boolean = false
) {
    Row(
        modifier = modifier
            .fillMaxWidth()
            .padding(vertical = 6.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.Top
    ) {
        Text(
            text = keyLabel,
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            modifier = Modifier.weight(0.42f)
        )
        Spacer(modifier = Modifier.width(8.dp))
        Text(
            text = valueText,
            style = if (monoValue) MonoTextStyle else MaterialTheme.typography.bodyMedium.copy(fontWeight = FontWeight.Medium),
            color = MaterialTheme.colorScheme.onSurface,
            modifier = Modifier.weight(0.58f)
        )
    }
}
